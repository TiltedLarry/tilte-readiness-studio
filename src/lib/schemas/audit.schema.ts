import { z } from "zod";

// 0. Audit Request Input
export const AuditInputSchema = z.object({
  campaignId: z.string().optional(),
  subjectLine: z.string().min(1, "Subject line is required"),
  preHeader: z.string().default(""),
  emailCopy: z.string().min(1, "Email copy is required"),
  styleGuideId: z.string().optional(),
  pngUrl: z.string().url().optional(),
  pngBase64: z.string().optional(),
  pngMimeType: z.string().optional(),
});

// 1. Individual Rule Evaluation (Returned by AI Auditors)
export const RuleEvaluationSchema = z.object({
  ruleId: z.string().describe("Must match the exact ruleId from the backend rubric"),
  passed: z.boolean().describe("True only if the email strictly satisfies the rule criteria"),
  severity: z.enum(["critical", "warning", "info"]),
  finding: z.string().describe("1-sentence factual explanation of what was found"),
  evidence: z.string().describe("Exact quote from copy OR exact visual coordinates/area in the PNG"),
  suggestedFix: z
    .string()
    .describe("Actionable, specific edit to resolve the issue (empty if passed)"),
});

// 2. Pipeline A Output: Copy & Subject Line Audit
export const CopyAuditOutputSchema = z.object({
  evaluations: z.array(RuleEvaluationSchema),
  detectedReadingGrade: z.number(),
  spamTriggerWordsFound: z.array(z.string()),
});

// 3. Pipeline B Output: Inbox AI Summary & Truncation Simulator
export const InboxSimulationOutputSchema = z.object({
  appleMailAiSummary: z
    .string()
    .max(140)
    .describe("Realistic 2-line AI preview summary generated by Apple Mail/Gmail"),
  mobileSubjectTruncated: z
    .string()
    .describe("How the subject line renders cut off at 35 characters"),
  desktopSubjectTruncated: z
    .string()
    .describe("How the subject line renders cut off at 60 characters"),
  summarySentiment: z.enum(["compelling", "neutral", "misleading", "spammy"]),
  summaryCritique: z
    .string()
    .describe("Does the AI summary accurately preserve the email's main value proposition?"),
});

// 4. Pipeline C Output: Multimodal Figma PNG vs. Style Guide Audit
export const VisualAuditOutputSchema = z.object({
  evaluations: z.array(RuleEvaluationSchema),
  estimatedImageToTextRatio: z.string().describe("e.g., '60% Image / 40% Text'"),
  primaryCtaAboveFold: z
    .boolean()
    .describe("Whether the main CTA button appears within the top 600px"),
  detectedHexColors: z.array(z.string()).describe("Dominant hex colors extracted from the Figma PNG"),
});

// 5. Final Combined Report (Saved to DB & Rendered in UI)
export const FinalAuditReportSchema = z.object({
  campaignId: z.string(),
  campaignName: z.string().optional(),
  thumbnailDataUrl: z.string().optional(),
  createdAt: z.string(),
  overallScore: z.number().min(0).max(100),
  readinessStatus: z.enum(["READY_TO_SEND", "NEEDS_REVISION", "BLOCKED"]),
  categoryScores: z.object({
    copyAndAlignment: z.number(),
    visualAndBrand: z.number(),
    complianceAndDeliverability: z.number(),
  }),
  inboxSimulation: InboxSimulationOutputSchema,
  evaluations: z.array(
    RuleEvaluationSchema.extend({
      category: z.enum(["copy", "visual", "compliance"]),
      weight: z.number(),
      ruleTitle: z.string(),
    })
  ),
});

export type AuditInput = z.infer<typeof AuditInputSchema>;
export type RuleEvaluation = z.infer<typeof RuleEvaluationSchema>;
export type CopyAuditOutput = z.infer<typeof CopyAuditOutputSchema>;
export type InboxSimulationOutput = z.infer<typeof InboxSimulationOutputSchema>;
export type VisualAuditOutput = z.infer<typeof VisualAuditOutputSchema>;
export type FinalAuditReport = z.infer<typeof FinalAuditReportSchema>;
